"""Build a queryable dimensional warehouse from the PostgreSQL gold marts."""

import psycopg

WAREHOUSE_SCHEMA = "warehouse"

TABLE_DDL = (
    """
    CREATE TABLE IF NOT EXISTS warehouse.dim_date (
        date_key INTEGER PRIMARY KEY,
        full_date DATE NOT NULL UNIQUE,
        day_of_week SMALLINT NOT NULL,
        month SMALLINT NOT NULL,
        quarter SMALLINT NOT NULL,
        year SMALLINT NOT NULL
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS warehouse.dim_store (
        store_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        store_id TEXT NOT NULL UNIQUE,
        store_name TEXT,
        county TEXT,
        region TEXT NOT NULL
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS warehouse.dim_product (
        product_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        product_id TEXT NOT NULL UNIQUE,
        product_name TEXT,
        category TEXT,
        market_mapping_code TEXT,
        base_unit TEXT,
        quantity_per_unit DOUBLE PRECISION
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS warehouse.dim_market (
        market_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        market_name TEXT NOT NULL,
        county TEXT NOT NULL,
        UNIQUE (market_name, county)
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS warehouse.fact_sales_by_store (
        date_key INTEGER NOT NULL REFERENCES warehouse.dim_date(date_key),
        store_key BIGINT NOT NULL REFERENCES warehouse.dim_store(store_key),
        payment_method TEXT NOT NULL,
        transaction_count BIGINT NOT NULL,
        units_sold BIGINT NOT NULL,
        gross_sales DOUBLE PRECISION NOT NULL,
        PRIMARY KEY (date_key, store_key, payment_method)
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS warehouse.fact_sales (
        transaction_id TEXT NOT NULL,
        line_number INTEGER NOT NULL,
        date_key INTEGER NOT NULL REFERENCES warehouse.dim_date(date_key),
        store_key BIGINT NOT NULL REFERENCES warehouse.dim_store(store_key),
        product_key BIGINT NOT NULL REFERENCES warehouse.dim_product(product_key),
        quantity_sold BIGINT NOT NULL,
        unit_price DOUBLE PRECISION NOT NULL,
        total_amount DOUBLE PRECISION NOT NULL,
        base_quantity_sold DOUBLE PRECISION NOT NULL,
        unit_price_per_base_unit DOUBLE PRECISION NOT NULL,
        PRIMARY KEY (transaction_id, line_number)
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS warehouse.fact_sales_by_product (
        date_key INTEGER NOT NULL REFERENCES warehouse.dim_date(date_key),
        product_key BIGINT NOT NULL REFERENCES warehouse.dim_product(product_key),
        transaction_count BIGINT NOT NULL,
        units_sold BIGINT NOT NULL,
        gross_sales DOUBLE PRECISION NOT NULL,
        PRIMARY KEY (date_key, product_key)
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS warehouse.fact_inventory_position (
        store_key BIGINT NOT NULL REFERENCES warehouse.dim_store(store_key),
        product_key BIGINT NOT NULL REFERENCES warehouse.dim_product(product_key),
        on_hand_quantity BIGINT NOT NULL,
        delivered_quantity BIGINT NOT NULL,
        sold_quantity BIGINT NOT NULL,
        PRIMARY KEY (store_key, product_key)
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS warehouse.fact_market_prices (
        market_price_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        date_key INTEGER NOT NULL REFERENCES warehouse.dim_date(date_key),
        market_key BIGINT NOT NULL REFERENCES warehouse.dim_market(market_key),
        product_key BIGINT REFERENCES warehouse.dim_product(product_key),
        commodity TEXT NOT NULL,
        classification TEXT,
        grade TEXT,
        sex TEXT,
        price_unit TEXT,
        wholesale_price DOUBLE PRECISION,
        retail_price DOUBLE PRECISION,
        price_basis_unit TEXT,
        wholesale_price_per_base_unit DOUBLE PRECISION,
        retail_price_per_base_unit DOUBLE PRECISION,
        wholesale_price_per_kg DOUBLE PRECISION,
        retail_price_per_kg DOUBLE PRECISION,
        supply_volume DOUBLE PRECISION
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS warehouse.fact_cpi_inflation (
        date_key INTEGER NOT NULL REFERENCES warehouse.dim_date(date_key),
        series_id TEXT NOT NULL,
        series_name TEXT,
        weight_pct DOUBLE PRECISION,
        month_on_month_pct DOUBLE PRECISION,
        yoy_inflation_pct DOUBLE PRECISION,
        PRIMARY KEY (date_key, series_id)
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS warehouse.fact_macro_indicators (
        date_key INTEGER NOT NULL REFERENCES warehouse.dim_date(date_key),
        series_id TEXT NOT NULL,
        series_name TEXT,
        cpi_index DOUBLE PRECISION,
        inflation_rate_yoy DOUBLE PRECISION,
        month_on_month_pct DOUBLE PRECISION,
        weight_pct DOUBLE PRECISION,
        PRIMARY KEY (date_key, series_id)
    )
    """,
)

FACT_TABLES = (
    "fact_sales_by_store",
    "fact_sales_by_product",
    "fact_inventory_position",
    "fact_market_prices",
    "fact_cpi_inflation",
    "fact_sales",
    "fact_macro_indicators",
)


def build_warehouse_model(cursor: psycopg.Cursor) -> None:
    """Refresh warehouse dimensions and facts from staged silver and gold data."""
    cursor.execute("CREATE SCHEMA IF NOT EXISTS warehouse")
    cursor.execute("DROP TABLE IF EXISTS warehouse.fact_market_prices")
    for statement in TABLE_DDL:
        cursor.execute(statement)
    cursor.execute(
        """
        ALTER TABLE warehouse.dim_product
            ADD COLUMN IF NOT EXISTS base_unit TEXT,
            ADD COLUMN IF NOT EXISTS quantity_per_unit DOUBLE PRECISION
        """
    )
    cursor.execute(
        """
        ALTER TABLE warehouse.fact_sales
            ADD COLUMN IF NOT EXISTS base_quantity_sold DOUBLE PRECISION,
            ADD COLUMN IF NOT EXISTS unit_price_per_base_unit DOUBLE PRECISION
        """
    )
    cursor.execute(
        """
        CREATE UNIQUE INDEX IF NOT EXISTS uq_fact_market_prices_grain
        ON warehouse.fact_market_prices (
            date_key,
            market_key,
            commodity,
            COALESCE(classification, ''),
            COALESCE(grade, ''),
            COALESCE(sex, ''),
            COALESCE(price_unit, '')
        )
        """
    )

    for table_name in FACT_TABLES:
        cursor.execute(f"DELETE FROM warehouse.{table_name}")

    cursor.execute(
        """
        INSERT INTO warehouse.dim_store (store_id, store_name, county, region)
        WITH store_ids AS (
            SELECT store_id
            FROM gold.sales_daily_by_store
            WHERE store_id IS NOT NULL
            UNION
            SELECT store_id
            FROM gold.inventory_position
            WHERE store_id IS NOT NULL
        ),
        store_attributes AS (
            SELECT store_id, MIN(store_name) AS store_name, MIN(county) AS county
            FROM gold.sales_daily_by_store
            WHERE store_id IS NOT NULL
            GROUP BY store_id
        )
        SELECT
            ids.store_id,
            attrs.store_name,
            attrs.county,
            CASE
                WHEN LOWER(COALESCE(attrs.county, '')) = 'nairobi' THEN 'Nairobi'
                WHEN LOWER(COALESCE(attrs.county, '')) = 'mombasa' THEN 'Coast'
                WHEN LOWER(COALESCE(attrs.county, '')) IN ('nakuru', 'uasin gishu')
                    THEN 'Rift Valley'
                WHEN LOWER(COALESCE(attrs.county, '')) = 'kisumu' THEN 'Nyanza'
                ELSE COALESCE(attrs.county, 'Unknown')
            END
        FROM store_ids AS ids
        LEFT JOIN store_attributes AS attrs USING (store_id)
        ON CONFLICT (store_id) DO UPDATE SET
            store_name = EXCLUDED.store_name,
            county = EXCLUDED.county,
            region = EXCLUDED.region
        """
    )

    cursor.execute(
        """
        INSERT INTO warehouse.dim_product (
            product_id, product_name, category, market_mapping_code,
            base_unit, quantity_per_unit
        )
        WITH product_ids AS (
            SELECT product_id
            FROM gold.sales_daily_by_product
            WHERE product_id IS NOT NULL
            UNION
            SELECT product_id
            FROM gold.inventory_position
            WHERE product_id IS NOT NULL
        ),
        product_attributes AS (
            SELECT
                product_id,
                MIN(product_name) AS product_name,
                MIN(category) AS category
            FROM gold.sales_daily_by_product
            WHERE product_id IS NOT NULL
            GROUP BY product_id
        ),
        product_measurements (
            product_id, market_mapping_code, quantity_per_unit, base_unit
        ) AS (
            VALUES
                ('P01', 'Maize Flour', 2.0::DOUBLE PRECISION, 'kg'),
                ('P02', 'Rice', 1.0::DOUBLE PRECISION, 'kg'),
                ('P03', 'Wheat Flour', 1.0::DOUBLE PRECISION, 'kg'),
                ('P04', NULL, 1.0::DOUBLE PRECISION, 'l'),
                ('P05', 'Sugar', 1.0::DOUBLE PRECISION, 'kg'),
                ('P06', NULL, 0.5::DOUBLE PRECISION, 'kg'),
                ('P07', NULL, 1.0::DOUBLE PRECISION, 'l'),
                ('P08', 'Tomatoes', 1.0::DOUBLE PRECISION, 'kg'),
                ('P09', NULL, 1.0::DOUBLE PRECISION, 'kg'),
                ('P10', NULL, 1.0::DOUBLE PRECISION, 'each'),
                ('P11', NULL, 1.0::DOUBLE PRECISION, 'kg'),
                ('P12', NULL, 0.4::DOUBLE PRECISION, 'kg')
        )
        SELECT
            ids.product_id,
            attrs.product_name,
            attrs.category,
            measurements.market_mapping_code,
            measurements.base_unit,
            measurements.quantity_per_unit
        FROM product_ids AS ids
        LEFT JOIN product_attributes AS attrs USING (product_id)
        LEFT JOIN product_measurements AS measurements USING (product_id)
        ON CONFLICT (product_id) DO UPDATE SET
            product_name = EXCLUDED.product_name,
            category = EXCLUDED.category,
            market_mapping_code = EXCLUDED.market_mapping_code,
            base_unit = EXCLUDED.base_unit,
            quantity_per_unit = EXCLUDED.quantity_per_unit
        """
    )

    cursor.execute(
        """
        INSERT INTO warehouse.dim_market (market_name, county)
        SELECT DISTINCT
            COALESCE(market, 'Unknown'),
            COALESCE(county, 'Unknown')
        FROM stage_market_prices
        ON CONFLICT (market_name, county) DO NOTHING
        """
    )

    cursor.execute(
        """
        INSERT INTO warehouse.dim_date (
            date_key, full_date, day_of_week, month, quarter, year
        )
        WITH source_dates AS (
            SELECT sale_date AS full_date FROM gold.sales_daily_by_store
            UNION
            SELECT sale_date FROM gold.sales_daily_by_product
            UNION
            SELECT survey_date FROM gold.kamis_latest_market_prices
            UNION
            SELECT period_date FROM gold.knbs_latest_cpi_inflation
            UNION
            SELECT sale_date FROM stage_sales_lines
            UNION
            SELECT survey_date FROM stage_market_prices
            UNION
            SELECT period_date FROM stage_macro_indicators
        ),
        date_bounds AS (
            SELECT MIN(full_date) AS first_date, MAX(full_date) AS last_date
            FROM source_dates
        ),
        calendar AS (
            SELECT generated_date::DATE AS full_date
            FROM date_bounds,
                LATERAL GENERATE_SERIES(first_date, last_date, INTERVAL '1 day')
                    AS generated_dates(generated_date)
        )
        SELECT
            TO_CHAR(calendar.full_date, 'YYYYMMDD')::INTEGER,
            calendar.full_date,
            EXTRACT(ISODOW FROM calendar.full_date)::SMALLINT,
            EXTRACT(MONTH FROM calendar.full_date)::SMALLINT,
            EXTRACT(QUARTER FROM calendar.full_date)::SMALLINT,
            EXTRACT(YEAR FROM calendar.full_date)::SMALLINT
        FROM calendar
        WHERE full_date IS NOT NULL
        ON CONFLICT (date_key) DO NOTHING
        """
    )

    cursor.execute(
        """
        INSERT INTO warehouse.fact_sales (
            transaction_id, line_number, date_key, store_key, product_key,
            quantity_sold, unit_price, total_amount, base_quantity_sold,
            unit_price_per_base_unit
        )
        SELECT
            g.transaction_id,
            g.line_number,
            d.date_key,
            s.store_key,
            p.product_key,
            g.quantity_sold,
            g.unit_price,
            g.total_amount,
            g.quantity_sold * p.quantity_per_unit,
            g.unit_price / NULLIF(p.quantity_per_unit, 0)
        FROM stage_sales_lines AS g
        JOIN warehouse.dim_date AS d ON d.full_date = g.sale_date
        JOIN warehouse.dim_store AS s ON s.store_id = g.store_id
        JOIN warehouse.dim_product AS p ON p.product_id = g.product_id
        """
    )

    cursor.execute(
        """
        INSERT INTO warehouse.fact_sales_by_store (
            date_key, store_key, payment_method,
            transaction_count, units_sold, gross_sales
        )
        SELECT
            d.date_key,
            s.store_key,
            COALESCE(g.payment_method, 'Unknown'),
            g.transaction_count,
            g.units_sold,
            g.gross_sales
        FROM gold.sales_daily_by_store AS g
        JOIN warehouse.dim_date AS d ON d.full_date = g.sale_date
        JOIN warehouse.dim_store AS s ON s.store_id = g.store_id
        """
    )

    cursor.execute(
        """
        INSERT INTO warehouse.fact_sales_by_product (
            date_key, product_key, transaction_count, units_sold, gross_sales
        )
        SELECT
            d.date_key,
            p.product_key,
            g.transaction_count,
            g.units_sold,
            g.gross_sales
        FROM gold.sales_daily_by_product AS g
        JOIN warehouse.dim_date AS d ON d.full_date = g.sale_date
        JOIN warehouse.dim_product AS p ON p.product_id = g.product_id
        """
    )

    cursor.execute(
        """
        INSERT INTO warehouse.fact_inventory_position (
            store_key, product_key, on_hand_quantity,
            delivered_quantity, sold_quantity
        )
        SELECT
            s.store_key,
            p.product_key,
            g.on_hand_quantity,
            g.delivered_quantity,
            g.sold_quantity
        FROM gold.inventory_position AS g
        JOIN warehouse.dim_store AS s ON s.store_id = g.store_id
        JOIN warehouse.dim_product AS p ON p.product_id = g.product_id
        """
    )

    cursor.execute(
        """
        INSERT INTO warehouse.fact_market_prices (
            date_key, market_key, product_key, commodity, classification, grade,
            sex, price_unit, wholesale_price, retail_price, price_basis_unit,
            wholesale_price_per_base_unit, retail_price_per_base_unit,
            wholesale_price_per_kg, retail_price_per_kg, supply_volume
        )
        SELECT
            d.date_key,
            m.market_key,
            p.product_key,
            COALESCE(g.commodity, 'Unknown'),
            g.classification,
            g.grade,
            g.sex,
            g.unit,
            g.wholesale_price,
            g.retail_price,
            CASE
                WHEN LOWER(TRIM(COALESCE(g.unit, '')))
                    IN ('kg', 'kilogram', 'kilograms') THEN 'kg'
                WHEN LOWER(TRIM(COALESCE(g.unit, '')))
                    IN ('l', 'lt', 'liter', 'litre', 'liters', 'litres') THEN 'l'
            END,
            CASE
                WHEN LOWER(TRIM(COALESCE(g.unit, '')))
                    IN ('kg', 'kilogram', 'kilograms') THEN g.wholesale_price
                WHEN LOWER(TRIM(COALESCE(g.unit, '')))
                    IN ('l', 'lt', 'liter', 'litre', 'liters', 'litres')
                    THEN g.wholesale_price
            END,
            CASE
                WHEN LOWER(TRIM(COALESCE(g.unit, '')))
                    IN ('kg', 'kilogram', 'kilograms') THEN g.retail_price
                WHEN LOWER(TRIM(COALESCE(g.unit, '')))
                    IN ('l', 'lt', 'liter', 'litre', 'liters', 'litres')
                    THEN g.retail_price
            END,
            CASE
                WHEN LOWER(TRIM(COALESCE(g.unit, ''))) IN ('kg', 'kilogram', 'kilograms')
                    THEN g.wholesale_price
            END,
            CASE
                WHEN LOWER(TRIM(COALESCE(g.unit, ''))) IN ('kg', 'kilogram', 'kilograms')
                    THEN g.retail_price
            END,
            g.supply_volume
        FROM stage_market_prices AS g
        JOIN warehouse.dim_date AS d ON d.full_date = g.survey_date
        JOIN warehouse.dim_market AS m
            ON m.market_name = COALESCE(g.market, 'Unknown')
            AND m.county = COALESCE(g.county, 'Unknown')
        LEFT JOIN warehouse.dim_product AS p
            ON LOWER(TRIM(p.market_mapping_code)) = LOWER(TRIM(g.commodity))
        """
    )

    cursor.execute(
        """
        INSERT INTO warehouse.fact_macro_indicators (
            date_key, series_id, series_name, cpi_index,
            inflation_rate_yoy, month_on_month_pct, weight_pct
        )
        SELECT
            d.date_key,
            g.series_id,
            g.series_name,
            NULL,
            g.yoy_inflation_pct,
            g.month_on_month_pct,
            g.weight_pct
        FROM stage_macro_indicators AS g
        JOIN warehouse.dim_date AS d ON d.full_date = g.period_date
        """
    )

    cursor.execute(
        """
        INSERT INTO warehouse.fact_cpi_inflation (
            date_key, series_id, series_name, weight_pct,
            month_on_month_pct, yoy_inflation_pct
        )
        SELECT
            d.date_key,
            g.series_id,
            g.series_name,
            g.weight_pct,
            g.month_on_month_pct,
            g.yoy_inflation_pct
        FROM gold.knbs_latest_cpi_inflation AS g
        JOIN warehouse.dim_date AS d ON d.full_date = g.period_date
        """
    )
